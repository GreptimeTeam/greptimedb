    #[test]
    fn procedure_event_only_records_context_on_submission() {
        let context = ProcedureContext {
            actor: Some("alice".to_string()),
            event_context: Some(PersistentEventContext::new(TriggerReason::AutoRepartition)),
        };
        let submitted = ProcedureEvent::new_with_context(
            ProcedureId::random(),
            Box::new(TestEvent {}),
            ProcedureState::Running,
            EventTrigger::Submitted,
            context.clone(),
        );
        let succeeded = ProcedureEvent::new_with_context(
            ProcedureId::random(),
            Box::new(TestEvent {}),
            ProcedureState::Done { output: None },
            EventTrigger::Succeeded,
            context,
        );

        assert_eq!(
            submitted.extra_rows().unwrap()[0].values[0],
            ValueData::StringValue("alice".to_string()).into()
        );
        assert_eq!(
            succeeded.extra_rows().unwrap()[0].values[0],
            ValueData::StringValue("alice".to_string()).into()
        );
        assert_eq!(
            submitted.extra_rows().unwrap()[0].values[6],
            jsonb_value(&json!({"reason": "auto_repartition"}))
        );
        assert_eq!(
            succeeded.extra_rows().unwrap()[0].values[6],
            Value { value_data: None }
        );
    }

    #[test]
    fn test_event_trigger_serialization() {
        let procedure_id = ProcedureId::parse_str("00000000-0000-0000-0000-000000000001").unwrap();

        for (trigger, name) in [
            (EventTrigger::Submitted, "Submitted"),
            (EventTrigger::Recovered, "Recovered"),
            (EventTrigger::RollingBack, "RollingBack"),
            (EventTrigger::Succeeded, "Succeeded"),
            (EventTrigger::Failed, "Failed"),
            (EventTrigger::Poisoned, "Poisoned"),
        ] {
            assert_eq!(
                serde_json::to_value(trigger).unwrap(),
                json!({"type": name})
            );
        }
        assert_eq!(
            serde_json::to_value(EventTrigger::ChildSubmitted {
                procedure_id,
                outcome: ChildSubmissionOutcome::Accepted,
            })
            .unwrap(),
            json!({
                "type": "ChildSubmitted",
                "procedure_id": "00000000-0000-0000-0000-000000000001",
                "outcome": "Accepted",
            })
        );
        assert_eq!(
            serde_json::to_value(EventTrigger::Retrying {
                phase: RetryPhase::Execute,
                attempt: 2,
            })
            .unwrap(),
            json!({"type": "Retrying", "phase": "Execute", "attempt": 2})
        );
    }
